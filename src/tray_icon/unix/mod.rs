#[derive(Debug)]
struct TrayIcon {
    // For calling list_players() inside main thread.
    req_tx: async_channel::Sender<()>,
    resp_rx: async_channel::Receiver<Vec<PlayerId>>,
}

impl TrayIcon {
    pub fn new(
        req_tx: async_channel::Sender<()>,
        resp_rx: async_channel::Receiver<Vec<PlayerId>>,
    ) -> Self {
        Self { req_tx, resp_rx }
    }
}

