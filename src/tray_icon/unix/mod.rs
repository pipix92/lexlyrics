fn find_in_path(program: &str) -> Option<std::path::PathBuf> {
    let path = env::var_os("PATH")?;
    env::split_paths(&path)
        .map(|dir| dir.join(program))
        .find(|candidate| candidate.is_file())
}

/// `lexlyrics-theme` from PATH, falling back to the usual install locations:
/// a session started from the desktop often lacks `~/.local/bin` in PATH.
fn theme_tool_path() -> Option<std::path::PathBuf> {
    find_in_path(THEME_TOOL).or_else(|| {
        let home = env::var_os("HOME").map(std::path::PathBuf::from);
        home.map(|home| home.join(".local/bin").join(THEME_TOOL))
            .into_iter()
            .chain([std::path::PathBuf::from("/usr/bin").join(THEME_TOOL)])
            .find(|candidate| candidate.is_file())
    })
}

/// Open the customization TUI in a terminal.
///
/// `$LEXLYRICS_TERMINAL` picks the terminal (the tool is appended as its last
/// argument, e.g. `LEXLYRICS_TERMINAL="cosmic-term -e"`), otherwise the first
/// known one found in PATH is used.
fn open_theme_tool() {
    let Some(tool) = theme_tool_path() else {
        error!("{THEME_TOOL} not found, install it to ~/.local/bin or /usr/bin");
        return;
    };

    let mut command = if let Ok(custom) = env::var("LEXLYRICS_TERMINAL") {
        let mut words = custom.split_whitespace();
        let Some(program) = words.next() else {
            error!("LEXLYRICS_TERMINAL is empty");
            return;
        };
        let mut command = process::Command::new(program);
        command.args(words);
        command
    } else {
        // terminal, and the arguments that make it run a command
        const TERMINALS: [(&str, &[&str]); 5] = [
            ("kitty", &["--title", "LexLyrics"]),
            ("konsole", &["-e"]),
            ("x-terminal-emulator", &["-e"]),
            ("cosmic-term", &["-e"]),
            ("xterm", &["-title", "LexLyrics", "-e"]),
        ];
        let Some((terminal, args)) = TERMINALS
            .iter()
            .find(|(terminal, _)| find_in_path(terminal).is_some())
        else {
            error!("no terminal emulator found, set LEXLYRICS_TERMINAL");
            return;
        };
        let mut command = process::Command::new(terminal);
        command.args(*args);
        command
    };

    if let Err(e) = command.arg(&tool).spawn() {
        error!("failed to open {THEME_TOOL}: {e}");
    }
}

/// Switch between the compact OSD bar and the fullscreen HUD.
///
/// The two modes are set up very differently at startup, so the choice is
/// saved and LexLyrics restarts into it.
fn set_window_mode(fullscreen: bool) {
    crate::config::save_bool("start-fullscreen", fullscreen);
    restart_myself();
}

fn restart_myself() {
    let my_path = env::args().next().unwrap();
    let Ok(_) = process::Command::new("sh")
        .arg("-c")
        .arg(format!("sleep 1 && {my_path}"))
        .spawn()
    else {
        error!("failed to run waylyrics");
        return;
    };
    let _ = ui_action().send_blocking(UIAction::Quit);
}
